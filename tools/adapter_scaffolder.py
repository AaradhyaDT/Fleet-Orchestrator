"""Autonomous Adapter Scaffolder.

Scaffolds production-grade worker adapters implementing BaseWorkerAdapter along
with comprehensive pytest unit test suites.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from string import Template
from typing import Dict, Optional


ADAPTER_TEMPLATE = Template('''from __future__ import annotations

import os
from typing import Any
import httpx

from client.adapters.base_adapter import BaseWorkerAdapter


class ${class_name}(BaseWorkerAdapter):
    """
    Adapter for $provider_title ($model).
    Autonomous scaffold generated by Fleet Adapter Scaffolder.
    """

    def __init__(
        self,
        worker_id: str = "${provider_lower}-w1",
        nickname: str = "${provider_title} Worker",
        base_url: str = "${base_url}",
        model: str = "${model}",
        api_key: str | None = None,
    ):
        super().__init__(worker_id, nickname, ["research", "qa", "writing", "code"])
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.api_key = api_key or os.getenv("${env_key}", "")

    async def check_health(self) -> bool:
        """Probe provider endpoint for service availability."""
        try:
            headers = {"Authorization": f"Bearer {self.api_key}"} if self.api_key else {}
            async with httpx.AsyncClient(timeout=5.0) as client:
                r = await client.get(f"{self.base_url}/health", headers=headers)
                return r.status_code in (200, 204)
        except Exception:
            return False

    async def execute_task(
        self,
        task_id: str,
        spec: str,
        stage: str,
        context: dict[str, Any],
    ) -> dict[str, Any]:
        """Executes prompt against provider endpoint."""
        prompt = (
            f"SYSTEM: You are an autonomous specialist in {stage}.\\n"
            f"TASK SPEC:\\n{spec}\\n\\n"
            f"OUTPUT DELIVERABLE:"
        )

        headers = {
            "Content-Type": "application/json",
        }
        if self.api_key:
            headers["Authorization"] = f"Bearer {self.api_key}"

        payload = {
            "model": self.model,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": 0.2,
        }

        try:
            async with httpx.AsyncClient(timeout=120.0) as client:
                r = await client.post(
                    f"{self.base_url}/chat/completions",
                    headers=headers,
                    json=payload,
                )
                if r.status_code != 200:
                    return {
                        "summary": f"HTTP {r.status_code} error from ${provider_title}",
                        "result_text": "",
                        "success": False,
                        "error": r.text,
                    }

                data = r.json()
                content = data.get("choices", [{}])[0].get("message", {}).get("content", "")
                return {
                    "summary": f"Task executed cleanly via ${class_name}",
                    "result_text": content,
                    "success": True,
                    "error": None,
                }
        except Exception as e:
            return {
                "summary": f"Execution exception in ${class_name}",
                "result_text": "",
                "success": False,
                "error": str(e),
            }
''')


TEST_TEMPLATE = Template('''"""Unit tests for ${class_name}."""

import pytest
from unittest.mock import AsyncMock, patch, MagicMock
from client.adapters.${module_name} import ${class_name}


def test_${module_name}_init():
    adapter = ${class_name}(
        worker_id="${provider_lower}-test",
        nickname="Test Worker",
        model="${model}",
    )
    assert adapter.worker_id == "${provider_lower}-test"
    assert adapter.nickname == "Test Worker"
    assert adapter.model == "${model}"
    assert "research" in adapter.capabilities
    assert "code" in adapter.capabilities


@pytest.mark.asyncio
async def test_${module_name}_health():
    adapter = ${class_name}("${provider_lower}-w1", "Test Worker")

    mock_resp = MagicMock()
    mock_resp.status_code = 200

    with patch("httpx.AsyncClient.get", new_callable=AsyncMock) as mock_get:
        mock_get.return_value = mock_resp
        assert await adapter.check_health() is True

    with patch("httpx.AsyncClient.get", side_effect=Exception("Connection refused")):
        assert await adapter.check_health() is False


@pytest.mark.asyncio
async def test_${module_name}_execution_success():
    adapter = ${class_name}("${provider_lower}-w1", "Test Worker")

    mock_resp = MagicMock()
    mock_resp.status_code = 200
    mock_resp.json.return_value = {
        "choices": [{"message": {"content": "Sample output response."}}],
    }

    with patch("httpx.AsyncClient.post", new_callable=AsyncMock) as mock_post:
        mock_post.return_value = mock_resp
        res = await adapter.execute_task(
            task_id="task-scaffold-001",
            spec="Run test task",
            stage="qa",
            context={},
        )
        assert res["success"] is True
        assert res["result_text"] == "Sample output response."
        assert res["error"] is None


@pytest.mark.asyncio
async def test_${module_name}_execution_http_error():
    adapter = ${class_name}("${provider_lower}-w1", "Test Worker")

    mock_resp = MagicMock()
    mock_resp.status_code = 500
    mock_resp.text = "Internal Server Error"

    with patch("httpx.AsyncClient.post", new_callable=AsyncMock) as mock_post:
        mock_post.return_value = mock_resp
        res = await adapter.execute_task(
            task_id="task-scaffold-002",
            spec="Run failing task",
            stage="qa",
            context={},
        )
        assert res["success"] is False
        assert "500" in res["summary"]
        assert res["error"] == "Internal Server Error"
''')


def scaffold_adapter(
    provider: str,
    model: str = "default-model",
    class_name: Optional[str] = None,
    base_url: str = "https://api.example.com/v1",
    repo_root: Optional[Path] = None,
    force: bool = False,
    dry_run: bool = False,
) -> Dict[str, Path]:
    """Scaffold adapter and matching unit test files. Returns mapping of generated paths."""
    repo = repo_root or Path.cwd()
    provider_lower = provider.lower().replace("-", "_").replace(" ", "_")
    if not provider_lower.endswith("_adapter"):
        module_name = f"{provider_lower}_adapter"
    else:
        module_name = provider_lower
        provider_lower = provider_lower.replace("_adapter", "")

    provider_title = provider.replace("_", " ").replace("-", " ").title()

    if not class_name:
        parts = [p.capitalize() for p in provider_lower.split("_")]
        class_name = "".join(parts) + "Adapter"

    env_key = f"{provider_lower.upper()}_API_KEY"

    adapter_content = ADAPTER_TEMPLATE.substitute(
        provider_lower=provider_lower,
        provider_title=provider_title,
        class_name=class_name,
        model=model,
        base_url=base_url,
        env_key=env_key,
    )

    test_content = TEST_TEMPLATE.substitute(
        provider_lower=provider_lower,
        class_name=class_name,
        module_name=module_name,
        model=model,
    )

    adapter_path = repo / "client" / "adapters" / f"{module_name}.py"
    test_path = repo / "tests" / f"test_{module_name}.py"

    created: Dict[str, Path] = {}

    if dry_run:
        print(f"--- [DRY-RUN] Adapter file: {adapter_path} ---")
        print(f"--- [DRY-RUN] Test file:    {test_path} ---")
        return {"adapter": adapter_path, "test": test_path}

    if adapter_path.exists() and not force:
        print(f"[-] Adapter file already exists: {adapter_path} (use --force to overwrite)")
    else:
        adapter_path.parent.mkdir(parents=True, exist_ok=True)
        adapter_path.write_text(adapter_content, encoding="utf-8")
        created["adapter"] = adapter_path
        print(f"[+] Created adapter: {adapter_path.relative_to(repo)}")

    if test_path.exists() and not force:
        print(f"[-] Test file already exists: {test_path} (use --force to overwrite)")
    else:
        test_path.parent.mkdir(parents=True, exist_ok=True)
        test_path.write_text(test_content, encoding="utf-8")
        created["test"] = test_path
        print(f"[+] Created test:    {test_path.relative_to(repo)}")

    return created


def main() -> int:
    parser = argparse.ArgumentParser(description="Fleet Autonomous Adapter Scaffolder")
    parser.add_argument("--provider", required=True, help="Provider name (e.g. mistral, cohere, deepseek)")
    parser.add_argument("--model", default="default-model", help="Default model name")
    parser.add_argument("--class-name", help="Custom class name (e.g. MistralAdapter)")
    parser.add_argument("--base-url", default="https://api.example.com/v1", help="API base URL")
    parser.add_argument("--repo-root", default=".", help="Root of Fleet-Orchestrator")
    parser.add_argument("--force", action="store_true", help="Overwrite existing files")
    parser.add_argument("--dry-run", action="store_true", help="Simulate creation without writing files")
    args = parser.parse_args()

    repo = Path(args.repo_root).resolve()
    created = scaffold_adapter(
        provider=args.provider,
        model=args.model,
        class_name=args.class_name,
        base_url=args.base_url,
        repo_root=repo,
        force=args.force,
        dry_run=args.dry_run,
    )

    if created:
        print(f"\n[+] Successfully scaffolded {len(created)} file(s).")
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
